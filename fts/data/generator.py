OT_RATE = 38.0


def payroll(rng: np.random.Generator, mr: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, r in mr.iterrows():
        m = int(r["month"])
        seasonal = 1.0 + 0.08 * (BASE_OCC[m - 1] - 0.75) / 0.1
        for dept, (hc, cost) in DEPTS.items():
            var = dept in ("Rooms", "Food & Beverage", "Spa")
            b_hc = int(round(hc * (seasonal if var else 1.0)))
            a_hc = b_hc + int(rng.integers(-2, 3)) if var else b_hc + int(rng.integers(-1, 2))
            a_cost = cost * (1.0 + (0.025 if m >= 4 else 0.0)) * rng.normal(1, 0.006)  # April pay rise above plan
            b_ot = 320 if var else 40
            a_ot = int(b_ot * rng.normal(1.0, 0.12))
            if dept == "Rooms" and m in (6, 7, 8):
                a_ot = int(a_ot * 1.9)                   # housekeeping vacancies covered by overtime
            rows.append({
                "month": m, "month_name": MONTHS[m - 1], "department": dept,
                "headcount_budget": b_hc, "headcount_actual": a_hc,
                "avg_cost_per_fte_budget": round(cost, 2), "avg_cost_per_fte_actual": round(a_cost, 2),
                "overtime_hours_budget": b_ot, "overtime_hours_actual": a_ot,
                "payroll_budget": round(b_hc * cost + b_ot * OT_RATE, 2),
                "payroll_actual": round(a_hc * a_cost + a_ot * OT_RATE, 2),
            })
    return pd.DataFrame(rows)


