def renovation_cash_flows(c: dict) -> list[float]:
    """Incremental cash flows: year 0 capex, then uplift in room revenue
    x flow-through, plus a residual value in year 7."""
    rn = ROOMS * 365
    base_rev = rn * c["base_occupancy"] * c["base_adr"]
    new_rev = rn * (c["base_occupancy"] + c["occupancy_uplift_pts"]) * (c["base_adr"] + c["adr_uplift"])
    annual = (new_rev - base_rev) * c["flow_through"]
    flows = [-float(c["capex"])] + [annual] * c["years"]
    flows[-1] += c["terminal_value_year7"]
    return flows


