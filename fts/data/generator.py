TAX_RATE = 0.25
LOAN_OPENING = 30_000_000.0
LOAN_RATE = 0.06
LOAN_REPAY_MONTHLY = 125_000.0


def _pnl_month(m: int, rooms_rev: float, sold: int, group_rn: int, commissions: float,
               pay: dict[str, float], actual: bool, rng) -> dict[str, float]:
    noise = (lambda: rng.normal(1, 0.015)) if actual else (lambda: 1.0)
    fb = sold * 125.0 * noise() + group_rn * 70.0 * noise()
    spa = sold * 34.0 * noise()
    total = rooms_rev + fb + spa
    fb_cos_pct = 0.30 if not actual else (0.315 if m >= 9 else 0.302)
    util_base = 95_000 * (1 + 0.18 * (BASE_OCC[m - 1] - 0.75) / 0.1)
    if actual and m >= 6:
        util_base *= 1.12                                   # energy tariff increase
    pom_other = 45_000.0 + (120_000.0 if actual and m == 7 else 0.0)   # chiller repair
    L = {}
    L["Rooms revenue"] = rooms_rev
    L["Food & beverage revenue"] = fb
    L["Spa & other revenue"] = spa
    L["Rooms payroll"] = pay["Rooms"]
    L["Rooms other expenses"] = sold * 14.0 * noise() + commissions
    L["F&B cost of sales"] = fb * fb_cos_pct
    L["F&B payroll"] = pay["Food & Beverage"]
    L["F&B other expenses"] = fb * 0.08 * noise()
    L["Spa & other expenses"] = pay["Spa"] + spa * 0.18
    L["Administrative & general"] = pay["Administrative & General"] + 85_000 * noise()
    L["Sales & marketing"] = pay["Sales & Marketing"] + 60_000 * noise() + 0.015 * total
    L["Property operations & maintenance"] = pay["Property Operations"] + pom_other * noise()
    L["Utilities"] = util_base * noise()
    L = {k: round(v, 0) for k, v in L.items()}
    L["Total revenue"] = L["Rooms revenue"] + L["Food & beverage revenue"] + L["Spa & other revenue"]
    L["Management fee"] = round(0.03 * L["Total revenue"], 0)
    L["Insurance"] = 38_000.0
    L["Property tax"] = 52_000.0
    L["Depreciation"] = 260_000.0
    loan_bal = LOAN_OPENING - LOAN_REPAY_MONTHLY * (m - 1)
    L["Interest"] = round(loan_bal * LOAN_RATE / 12, 0)
    dept = ["Rooms payroll", "Rooms other expenses", "F&B cost of sales", "F&B payroll",
            "F&B other expenses", "Spa & other expenses"]
    und = ["Administrative & general", "Sales & marketing", "Property operations & maintenance",
           "Utilities"]
    L["Total departmental expenses"] = sum(L[k] for k in dept)
    L["Departmental profit"] = L["Total revenue"] - L["Total departmental expenses"]
    L["Total undistributed expenses"] = sum(L[k] for k in und)
    L["Gross operating profit (GOP)"] = L["Departmental profit"] - L["Total undistributed expenses"]
    L["EBITDA"] = L["Gross operating profit (GOP)"] - L["Management fee"] - L["Insurance"] - L["Property tax"]
    L["Profit before tax"] = L["EBITDA"] - L["Depreciation"] - L["Interest"]
    L["Income tax"] = round(L["Profit before tax"] * TAX_RATE, 0)   # loss months create a tax credit
    L["Net income"] = L["Profit before tax"] - L["Income tax"]
    return L


def monthly_pnl(rng, mr, ch, pay, rb) -> pd.DataFrame:
    rows = []
    for m in range(1, 13):
        r = mr[mr["month"] == m].iloc[0]
        b = rb[rb["month"] == m].iloc[0]
        p = pay[pay["month"] == m]
        commissions = ch[ch["month"] == m]["commission_cost"].sum()
        a_pay = dict(zip(p["department"], p["payroll_actual"]))
        b_pay = dict(zip(p["department"], p["payroll_budget"]))
        act = _pnl_month(m, float(r["room_revenue"]), int(r["sold_room_nights"]),
                         int(r["sold_group"]), commissions, a_pay, True, rng)
        # budget: same structure, budget mix of channels (pre-shock commission mix ~ 7.9%)
        b_sold = int(b["budget_sold_room_nights"])
        bud = _pnl_month(m, float(b["budget_room_revenue"]), b_sold, int(b_sold * 0.18),
                         float(b["budget_room_revenue"]) * 0.079, b_pay, False, rng)
        for line, _ in PNL_LINES:
            rows.append({"month": m, "month_name": MONTHS[m - 1], "line": line,
                         "line_type": LINE_TYPE[line], "actual": act[line], "budget": bud[line]})
    return pd.DataFrame(rows)


# ------------------------------------------- balance sheet & cash flow

def balance_sheet_and_cash_flow(pnl: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    def total(line):
        return float(pnl[pnl["line"] == line]["actual"].sum())

    ni, dep = total("Net income"), total("Depreciation")
    rev = total("Total revenue")
    open_bs = {"Cash": 3_200_000.0, "Accounts receivable": 1_150_000.0, "Inventories": 360_000.0,
               "Property, plant & equipment (net)": 62_000_000.0,
               "Accounts payable": 940_000.0, "Accrued expenses": 610_000.0,
               "Bank loan": LOAN_OPENING, "Share capital": 20_000_000.0}
    open_bs["Retained earnings"] = (open_bs["Cash"] + open_bs["Accounts receivable"]
                                    + open_bs["Inventories"] + open_bs["Property, plant & equipment (net)"]
                                    - open_bs["Accounts payable"] - open_bs["Accrued expenses"]
                                    - open_bs["Bank loan"] - open_bs["Share capital"])
    capex, dividends = 1_850_000.0, 1_000_000.0
    close = dict(open_bs)
    close["Accounts receivable"] = round(rev * 0.035, 0)     # ~13 days of revenue
    close["Inventories"] = 395_000.0
    close["Accounts payable"] = 1_010_000.0
    close["Accrued expenses"] = 640_000.0
    close["Property, plant & equipment (net)"] = open_bs["Property, plant & equipment (net)"] + capex - dep
    close["Bank loan"] = LOAN_OPENING - LOAN_REPAY_MONTHLY * 12
    close["Retained earnings"] = open_bs["Retained earnings"] + ni - dividends
    d_ar = close["Accounts receivable"] - open_bs["Accounts receivable"]
    d_inv = close["Inventories"] - open_bs["Inventories"]
    d_ap = close["Accounts payable"] - open_bs["Accounts payable"]
    d_acc = close["Accrued expenses"] - open_bs["Accrued expenses"]
    cfo = ni + dep - d_ar - d_inv + d_ap + d_acc
    cfi = -capex
    cff = -(LOAN_REPAY_MONTHLY * 12) - dividends
    close["Cash"] = open_bs["Cash"] + cfo + cfi + cff
    cf = pd.DataFrame([
        ("Net income", ni), ("Add back: depreciation", dep),
        ("(Increase) in accounts receivable", -d_ar), ("(Increase) in inventories", -d_inv),
        ("Increase in accounts payable", d_ap), ("Increase in accrued expenses", d_acc),
        ("Cash flow from operating activities", cfo),
        ("Capital expenditure", -capex), ("Cash flow from investing activities", cfi),
        ("Loan repayments", -(LOAN_REPAY_MONTHLY * 12)), ("Dividends paid", -dividends),
        ("Cash flow from financing activities", cff),
        ("Net change in cash", cfo + cfi + cff), ("Opening cash", open_bs["Cash"]),
        ("Closing cash", close["Cash"]),
    ], columns=["line", f"FY{YEAR}"])
    order = [("Cash", "Asset"), ("Accounts receivable", "Asset"), ("Inventories", "Asset"),
             ("Property, plant & equipment (net)", "Asset"), ("Accounts payable", "Liability"),
             ("Accrued expenses", "Liability"), ("Bank loan", "Liability"),
             ("Share capital", "Equity"), ("Retained earnings", "Equity")]
    bs = pd.DataFrame([{"line": k, "category": c, f"31-Dec-{YEAR - 1}": round(open_bs[k], 2),
                        f"31-Dec-{YEAR}": round(close[k], 2)} for k, c in order])
    return bs, cf.round(2)


# ------------------------------------------------- booking pace (Jan next year)

def booking_pace(rng, daily: pd.DataFrame) -> pd.DataFrame:
    d = daily.set_index(pd.to_datetime(daily["date"]))
    rows = []
    as_of = pd.Timestamp(f"{YEAR}-12-31")
    for stay in pd.date_range(f"{YEAR + 1}-01-01", periods=30, freq="D"):
        ly = stay - pd.Timedelta(days=364)                 # same weekday last year
        ly_actual = int(d.loc[ly, "rooms_sold"])
        days_out = (stay - as_of).days
        frac = 1 - 0.55 * (days_out / 30) ** 0.8
        ly_otb = int(round(ly_actual * frac * rng.normal(1, 0.03)))
        otb = int(round(ly_otb * 0.95 * rng.normal(1, 0.04)))  # pace ~5% behind last year
        weekend = stay.dayofweek in (4, 5)
        otb_adr = round(BASE_ADR[0] * (1.06 if weekend else 1.0) * 1.03 * rng.normal(1, 0.015), 2)
        rows.append({"stay_date": stay.date().isoformat(), "weekday": stay.day_name(),
                     "days_out": days_out, "rooms_available": ROOMS,
                     "on_the_books": min(otb, ROOMS), "otb_adr": otb_adr,
                     "ly_date": ly.date().isoformat(), "ly_on_the_books_same_time": ly_otb,
                     "ly_actual_sold": ly_actual})
    return pd.DataFrame(rows)


# ------------------------------------------------------ retail business

def retail_monthly(rng) -> pd.DataFrame:
    rows, ar, inv, ap = [], 40_000.0, 90_000.0, 35_000.0
    cash = 120_000.0
    for m in range(1, 13):
        rev = round(180_000 * (1 + 0.04 * (m - 1)) * rng.normal(1, 0.01), 0)
        cogs = round(rev * 0.55, 0)
        opex = 58_000.0
        dep = 5_000.0
        ni = rev - cogs - opex - dep
        new_ar = round(rev * (0.25 + 0.02 * m), 0)          # customers paying slower
        new_inv = round(90_000 + 22_000 * m, 0)               # building stock for new stores
        new_ap = round(cogs * 0.20, 0)
        cfo = ni + dep - (new_ar - ar) - (new_inv - inv) + (new_ap - ap)
        cash += cfo
        rows.append({"month": m, "month_name": MONTHS[m - 1], "revenue": rev,
                     "cost_of_goods_sold": cogs, "gross_profit": rev - cogs,
                     "operating_expenses": opex, "depreciation": dep, "net_income": ni,
                     "accounts_receivable": new_ar, "inventory": new_inv,
                     "accounts_payable": new_ap, "operating_cash_flow": round(cfo, 0),
                     "closing_cash": round(cash, 0)})
        ar, inv, ap = new_ar, new_inv, new_ap
    return pd.DataFrame(rows)


