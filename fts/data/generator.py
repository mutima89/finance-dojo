def write_all(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    ds = build()
    written = []
    for attr, name in FILES.items():
        p = out_dir / name
        getattr(ds, attr).to_csv(p, index=False, lineterminator="\n")   # same bytes on every OS
        written.append(p)
    p = out_dir / "commercial_cases.json"
    p.write_text(json.dumps(ds.cases, indent=2))
    written.append(p)
    readme = out_dir / "README_DATA.txt"
    readme.write_text(DATA_README)
    written.append(readme)
    return written


