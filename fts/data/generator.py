def _largest_remainder(total: int, weights: dict[str, float]) -> dict[str, int]:
    keys = list(weights)
    w = np.array([weights[k] for k in keys], dtype=float)
    w = w / w.sum()
    raw = w * total
    base = np.floor(raw).astype(int)
    rem = total - base.sum()
    order = np.argsort(-(raw - base))
    for i in order[:rem]:
        base[i] += 1
    return dict(zip(keys, base.tolist()))


# ------------------------------------------------------------ hotel daily

def hotel_daily(rng: np.random.Generator) -> pd.DataFrame:
    rows = []
    for d in pd.date_range(f"{YEAR}-01-01", f"{YEAR}-12-31", freq="D"):
        mi, dow = d.month - 1, d.dayofweek
        ooo = 0
        if pd.Timestamp(f"{YEAR}-02-10") <= d <= pd.Timestamp(f"{YEAR}-02-23"):
            ooo = 10                                     # soft-goods refresh on one floor
        elif rng.random() < 0.15:
            ooo = int(rng.integers(1, 4))
        avail = ROOMS - ooo
        weekend = dow in (4, 5)                          # Fri & Sat nights
        occ = BASE_OCC[mi] + DOW_ADJ[dow] + rng.normal(0, 0.035)
        shock = d >= SHOCK_START
        if shock and not weekend:
            occ -= 0.07                                  # corporate weakness on weekdays
        occ = float(np.clip(occ, 0.30, 0.995))
        sold = min(avail, int(round(occ * avail)))
        mix = dict(SEG_MIX_WEEKEND if weekend else SEG_MIX_WEEKDAY)
        if shock:
            mix["Corporate"] *= 0.75
        seg_rooms = _largest_remainder(sold, mix)
        rec = {"date": d.date().isoformat(), "weekday": d.day_name(),
               "day_type": "Weekend" if weekend else "Weekday",
               "rooms_in_inventory": ROOMS, "rooms_out_of_order": ooo,
               "rooms_available": avail, "rooms_sold": sold}
        total_rev = 0.0
        for s in SEGMENTS:
            mult = SEG_RATE[s] * (1.10 if weekend and s in ("Transient", "Leisure") else 1.0)
            if shock and s == "Transient":
                mult *= 0.94                             # tactical discounting on OTAs
            rate = BASE_ADR[mi] * mult * rng.normal(1, 0.02)
            rev = round(seg_rooms[s] * rate, 2)
            rec[f"sold_{s.lower()}"] = seg_rooms[s]
            rec[f"revenue_{s.lower()}"] = rev
            total_rev += rev
        rec["room_revenue"] = round(total_rev, 2)
        rec["cancellations"] = int(rng.poisson(max(sold * (0.08 if shock else 0.06), 0.1)))
        rec["no_shows"] = int(rng.poisson(max(sold * 0.012, 0.1)))
        rows.append(rec)
    df = pd.DataFrame(rows)
    cols = ["date", "weekday", "day_type", "rooms_in_inventory", "rooms_out_of_order",
            "rooms_available", "rooms_sold", "room_revenue", "cancellations", "no_shows"]
    cols += [f"sold_{s.lower()}" for s in SEGMENTS] + [f"revenue_{s.lower()}" for s in SEGMENTS]
    return df[cols]


def monthly_rooms(daily: pd.DataFrame) -> pd.DataFrame:
    d = daily.copy()
    d["month"] = pd.to_datetime(d["date"]).dt.month
    g = d.groupby("month").agg(
        available_room_nights=("rooms_available", "sum"),
        sold_room_nights=("rooms_sold", "sum"),
        room_revenue=("room_revenue", "sum"),
        cancellations=("cancellations", "sum"),
        **{f"sold_{s.lower()}": (f"sold_{s.lower()}", "sum") for s in SEGMENTS},
        **{f"revenue_{s.lower()}": (f"revenue_{s.lower()}", "sum") for s in SEGMENTS},
    ).reset_index()
    g["room_revenue"] = g["room_revenue"].round(2)
    for s in SEGMENTS:
        g[f"revenue_{s.lower()}"] = g[f"revenue_{s.lower()}"].round(2)
    g.insert(1, "month_name", [MONTHS[m - 1] for m in g["month"]])
    return g


def channel_monthly(mr: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, r in mr.iterrows():
        shock = r["month"] >= SHOCK_START.month
        ch_rooms = {c: 0 for c in CHANNELS}
        ch_rev = {c: 0.0 for c in CHANNELS}
        for s in SEGMENTS:
            split = dict(SEG_TO_CHANNEL[s])
            if shock and s == "Transient":
                split = {"Direct": 0.38, "OTA": 0.62}
            rn = int(r[f"sold_{s.lower()}"])
            rev = float(r[f"revenue_{s.lower()}"])
            alloc = _largest_remainder(rn, split)
            assigned = 0.0
            items = list(alloc.items())
            for i, (c, n) in enumerate(items):
                part = rev - assigned if i == len(items) - 1 else round(rev * n / rn, 2) if rn else 0.0
                ch_rooms[c] += n
                ch_rev[c] += part
                assigned += part
        for c in CHANNELS:
            rev = round(ch_rev[c], 2)
            rows.append({"month": int(r["month"]), "month_name": r["month_name"], "channel": c,
                         "room_nights": ch_rooms[c], "room_revenue": rev,
                         "commission_rate": COMMISSION[c],
                         "commission_cost": round(rev * COMMISSION[c], 2)})
    return pd.DataFrame(rows)


