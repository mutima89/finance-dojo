COMMON_MISTAKES = [
    ("Averaging daily ADRs or occupancies", "Always divide totals: total revenue / total rooms sold."),
    ("Showing ADR = $0 on a day with no sales", "ADR is undefined (n/a) when nothing is sold; RevPAR is $0."),
    ("Treating a missing value as zero", "Flag it and recover it from the source system; zero is a real value."),
    ("Using 150 x days instead of available room nights", "Subtract out-of-order rooms if your definition requires it, and say which you used."),
    ("Mixing up sold and available rooms", "Occupancy and RevPAR use AVAILABLE; ADR uses SOLD."),
    ("Calling every negative variance 'unfavorable'", "For expenses, a negative variance (below budget) is favorable."),
    ("Dividing variance % by actual", "Variance % is divided by budget."),
    ("Comparing costs to a static budget when volume changed", "Use a flexible budget for variable costs."),
    ("Typing numbers inside formulas (hard-coding)", "Put assumptions in labelled cells and reference them."),
    ("Forgetting $ when copying formulas", "Lock single assumption cells and fixed totals with $."),
    ("MATCH without the 0", "Use MATCH(value, range, 0) for exact matches."),
    ("Excel NPV discounting the investment", "Use =CF0 + NPV(rate, CF1:CFn)."),
    ("Judging a discount on revenue", "Judge it on total contribution after variable costs and extra costs."),
    ("Ranking competing projects by IRR", "Rank mutually exclusive projects by NPV."),
    ("Profit = cash", "Working capital and capex make cash differ from profit."),
    ("Presenting forecasts as certain", "State the method, key assumptions and a range."),
    ("Including sunk or non-incremental costs", "Only incremental cash flows belong in a decision."),
    ("Rounding too early", "Keep full precision; round only the final displayed figure."),
]

