"""Glossary, formula reference, common mistakes and interview questions."""

GLOSSARY = [
    ("Accrual accounting", "Recording revenue when earned and expenses when incurred, not when cash moves."),
    ("Accounts payable (AP)", "Money the business owes suppliers for goods or services already received."),
    ("Accounts receivable (AR)", "Money customers owe the business for goods or services already delivered."),
    ("ADR (Average Daily Rate)", "Room revenue / sold room nights. The average price of a sold room."),
    ("Ancillary revenue", "Non-room revenue: food & beverage, spa, parking, etc."),
    ("Available room nights", "Rooms x nights in the period, less out-of-order rooms."),
    ("Balance sheet", "Statement of assets, liabilities and equity at a single date."),
    ("Booking pace", "How fast reservations for a future date are arriving, compared with a benchmark (often last year)."),
    ("Break-even", "The volume or revenue at which total contribution exactly covers fixed costs (profit = 0)."),
    ("Budget", "The financial plan approved before the year starts, usually by month."),
    ("Cannibalisation", "Sales lost from existing products or full-price customers because of a new offer."),
    ("Capex (capital expenditure)", "Spending on long-lived assets (renovations, equipment). Shown in investing cash flow."),
    ("Cash conversion cycle", "DSO + DIO - DPO: days cash is tied up in operations."),
    ("Cash flow statement", "Shows cash generated and used in operating, investing and financing activities."),
    ("Channel", "How a booking was made: direct, OTA, GDS, wholesale."),
    ("Contribution margin", "Price - variable cost per unit; the amount each unit contributes to fixed costs and profit."),
    ("Cost of sales", "Direct cost of the goods sold, e.g. food cost in a restaurant."),
    ("Depreciation", "Spreading the cost of an asset over its useful life. A non-cash expense."),
    ("Discount rate", "The required rate of return used to convert future cash flows into today's value."),
    ("EBITDA", "Earnings before interest, tax, depreciation and amortisation."),
    ("Elasticity (price)", "% change in demand for a 1% change in price. Usually negative."),
    ("Equity", "Owners' share of the business: assets minus liabilities."),
    ("Favorable / Unfavorable (F/U)", "Whether a variance helps (F) or hurts (U) profit vs budget."),
    ("Fixed cost", "A cost that does not change with volume in the short term (insurance, salaried staff)."),
    ("Flexible budget", "Budget restated at the actual activity level, used to judge spending fairly."),
    ("Flow-through", "Share of incremental revenue that becomes incremental profit."),
    ("Forecast", "Current best estimate of future results; updated regularly."),
    ("FTE", "Full-time equivalent: a measure of headcount where two half-time staff = 1 FTE."),
    ("GDS", "Global Distribution System used by travel agents and corporate travel bookers."),
    ("GOP (Gross Operating Profit)", "Hotel profit after departmental and undistributed operating expenses."),
    ("Gross profit", "Revenue minus cost of sales."),
    ("Income statement (P&L)", "Revenue, expenses and profit over a period."),
    ("Incremental", "The difference caused by a decision (with vs without)."),
    ("IRR (Internal Rate of Return)", "Discount rate at which a project's NPV equals zero."),
    ("KPI", "Key performance indicator: a measure that tracks progress toward an objective."),
    ("Liabilities", "Obligations the business must settle (supplier invoices, loans)."),
    ("Margin of safety", "How far sales can fall before reaching break-even, as a % of sales."),
    ("Net ADR", "ADR after deducting distribution costs such as commission."),
    ("Net income (net profit)", "Profit after all expenses including interest and tax."),
    ("NPV (Net Present Value)", "Sum of a project's cash flows discounted to today, including the initial investment."),
    ("Occupancy", "Sold room nights / available room nights."),
    ("On the books (OTB)", "Reservations already confirmed for a future date."),
    ("Operating leverage", "Profit moves by a larger % than revenue because fixed costs do not flex."),
    ("OTA", "Online travel agency (third-party booking website) that charges commission."),
    ("Payback period", "Time until cumulative cash inflows repay the investment."),
    ("Pickup", "Rooms booked between a point in time and the arrival date."),
    ("RevPAR", "Room revenue / available room nights = occupancy x ADR."),
    ("ROI", "(Total return - investment) / investment."),
    ("Scenario analysis", "Testing outcomes under alternative sets of assumptions (base, upside, downside)."),
    ("Segment", "Type of guest: corporate, transient, group, leisure."),
    ("Sensitivity analysis", "Changing one input at a time to see its effect on an output."),
    ("Variable cost", "A cost that changes with volume (amenities per occupied room, food cost per cover)."),
    ("Variance", "Actual - Budget (or Actual - Forecast)."),
    ("Working capital", "Receivables + inventory - payables; cash tied up in day-to-day operations."),
]

